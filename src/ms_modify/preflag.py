"""
preflag.py — ms_apply_preflag

Applies deterministic pre-calibration flags in a single flagdata list-mode
pass, then splits calibrator fields to workdir/calibrators.ms.

Flagging steps (order matters — all combined in preflag_cmds.txt):
  1. Online flags from importasdm .flagonline.txt (if provided)
  2. Quack the start of each scan (mode='quack', quackinterval=quack_interval_s,
     quackmode='beg'); the first integrations read 4 to 17% low
  3. Shadow flags (mode='shadow', tolerance=shadow_tolerance_m)
  4. Zero-amplitude clip (mode='clip', clipzeros=True)
  5. Conservative tfcrop (mode='tfcrop', timecutoff=3.0, freqcutoff=3.0)
  6. Extend flags across polarizations (mode='extend', extendpols=True)

All six run via flagdata(mode='list', inpfile=preflag_cmds.txt, flagbackup=True)
in a single atomic pass. After flagging, calibrator fields are split to
workdir/calibrators.ms with keepflags=False.
"""

from __future__ import annotations

from pathlib import Path

from ms_inspect.util.casa_context import validate_ms_path
from ms_inspect.util.formatting import (
    field as fmt_field,
)
from ms_inspect.util.formatting import (
    normalize_field_sel,
    normalize_spw_sel,
    response_envelope,
)
from ms_inspect.util.logs import write_script
from ms_inspect.util.stage_log import record_stage
from ms_modify import debug_mode

TOOL_NAME = "ms_apply_preflag"
#: CASA tasks this tool calls; the valid debug_params keys (debug_mode.py).
DEBUG_TASKS = ("flagdata", "split")


def _build_cmds_content(
    online_flag_file: str,
    shadow_tolerance_m: float,
    do_tfcrop: bool,
    quack_interval_s: float = 5.0,
) -> str:
    """
    Build the text content for preflag_cmds.txt.

    Each line is a flagdata command in key=value format (flagdata list-mode
    syntax). Online flag file lines are prepended verbatim if provided.
    """
    lines: list[str] = []

    if online_flag_file:
        p = Path(online_flag_file)
        if p.exists():
            raw = p.read_text()
            # Include non-empty, non-comment lines verbatim
            for line in raw.splitlines():
                stripped = line.strip()
                if stripped and not stripped.startswith("#"):
                    lines.append(stripped)
        else:
            lines.append(f"# WARNING: online_flag_file not found: {online_flag_file}")

    if quack_interval_s > 0:
        lines.append(f"mode='quack' quackinterval={quack_interval_s} quackmode='beg'")
    lines.append(f"mode='shadow' tolerance={shadow_tolerance_m}")
    lines.append("mode='clip' clipzeros=True")
    if do_tfcrop:
        lines.append("mode='tfcrop' timecutoff=3.0 freqcutoff=3.0")
    lines.append("mode='extend' extendpols=True")

    return "\n".join(lines) + "\n"


_PREFLAG_HELPERS_SNIPPET = '''\
def _has_flag_version(vis, version_name="before_preflag"):
    """True if <vis>.flagversions already records version_name."""
    import os

    fv_dir = str(vis).rstrip("/") + ".flagversions"
    if os.path.exists(os.path.join(fv_dir, f"flags.{version_name}")):
        return True
    list_file = os.path.join(fv_dir, "FLAG_VERSION_LIST")
    if os.path.isfile(list_file):
        try:
            with open(list_file, errors="replace") as _fh:
                for _ln in _fh:
                    if ":" in _ln and _ln.split(":", 1)[0].strip() == version_name:
                        return True
        except OSError:
            pass
    return False


def _archive_cal_ms(cal_ms_path, src_ms_path, workdir_path):
    """Archive existing workdir/calibrators.ms to .attemptN before split."""
    import os

    if not os.path.exists(cal_ms_path):
        return
    if not workdir_path:
        raise RuntimeError("workdir is required to archive calibrators.ms.")
    real_cal = os.path.realpath(cal_ms_path)
    real_src = os.path.realpath(src_ms_path)
    real_wd = os.path.realpath(workdir_path)
    if (
        real_cal == real_src
        or os.path.dirname(real_cal) != real_wd
        or os.path.basename(real_cal) != "calibrators.ms"
    ):
        raise RuntimeError(
            f"Refusing to archive {cal_ms_path!r}: must resolve to "
            "workdir/calibrators.ms and not equal the input MS."
        )
    n = 1
    while os.path.exists(f"{cal_ms_path}.attempt{n}"):
        n += 1
    os.rename(cal_ms_path, f"{cal_ms_path}.attempt{n}")
'''

_pf_ns: dict = {}
exec(_PREFLAG_HELPERS_SNIPPET, _pf_ns)  # noqa: S102 - our own source, defined above
_has_flag_version = _pf_ns["_has_flag_version"]
_archive_cal_ms = _pf_ns["_archive_cal_ms"]


def _build_script(
    ms_str: str,
    cmds_path: str,
    cal_ms: str,
    cal_fields: str,
    workdir: str = "",
    spw: str = "",
) -> str:
    """Return a self-contained preflag + split Python script."""
    from ms_inspect.util.stage_log import RECORD_STAGE_SNIPPET as record

    spw_line = f"    spw={spw!r},\n" if spw else ""
    return f"""\
#!/usr/bin/env python
\"\"\"
Auto-generated by ms_apply_preflag (ms_modify).
Run with: python preflag.py
\"\"\"
from casatasks import flagdata, flagmanager, split

{record}
{_PREFLAG_HELPERS_SNIPPET}
ms_path = {ms_str!r}
cmds_file = {cmds_path!r}
cal_ms = {cal_ms!r}
cal_fields = {cal_fields!r}
workdir = {workdir!r}

# Step 1 -- Restore clean pre-preflag flags on retry, or save initial backup once.
if _has_flag_version(ms_path, "before_preflag"):
    flagmanager(vis=ms_path, mode="restore", versionname="before_preflag", merge="replace")
else:
    flagmanager(vis=ms_path, mode="save", versionname="before_preflag", comment="Pre-preflag state")

flagdata(
    vis=ms_path,
    mode="list",
    inpfile=cmds_file,
    flagbackup=False,
)
print("Preflagging done.")

# Step 2 -- Archive any stale calibrators.ms and split calibrator fields cleanly.
# keepflags=False drops flagged rows so downstream calibration never sees them.
_archive_cal_ms(cal_ms, ms_path, workdir)
split(
    vis=ms_path,
    outputvis=cal_ms,
    field=cal_fields,
{spw_line}    datacolumn="data",
    keepflags=False,
)
# Record both products only after split succeeds so a failed split leaves no
# half-completed preflag stage in stage_log.jsonl.
_summary = flagdata(vis=ms_path, mode="summary")
_flagged = (
    float(_summary["flagged"]) / float(_summary["total"]) if _summary.get("total") else None
)
_record_stage(workdir, "preflag", ms_path, {{"flagged_fraction": _flagged}})
_record_stage(workdir, "preflag", cal_ms)
print(f"Calibrator split complete: {{cal_ms}}")
"""


def run(
    ms_path: str,
    workdir: str,
    cal_fields: str,
    online_flag_file: str = "",
    shadow_tolerance_m: float = 0.0,
    do_tfcrop: bool = True,
    execute: bool = False,
    quack_interval_s: float = 5.0,
    spw: str = "",
    debug: bool = False,
    debug_params: dict | None = None,
) -> dict:
    """
    Apply deterministic pre-calibration flags and split calibrators.

    Args:
        ms_path:           Path to the full MS.
        workdir:           Existing output directory.
        cal_fields:        CASA field selection string for calibrators (required).
        online_flag_file:  Path to .flagonline.txt from importasdm (empty = skip).
        shadow_tolerance_m: Shadow tolerance in metres (default 0.0).
        do_tfcrop:         Apply conservative tfcrop pass (default True).
        quack_interval_s:  Seconds flagged at the start of each scan (default
                           5.0; 0 disables).
        execute:           If False (default), write scripts and return.
                           If True, run flagdata + split in-process.

    Returns:
        Standard response envelope. Always includes cmds_path and script_path.
        When execute=True, also includes flags_applied and cal_ms.
    """
    p = validate_ms_path(ms_path)
    ms_str = str(p)
    casa_calls: list[str] = []
    warnings: list[str] = []

    cal_fields = normalize_field_sel(cal_fields)
    spw = normalize_spw_sel(spw)
    workdir_path = Path(workdir)
    if not workdir_path.exists():
        from ms_inspect.exceptions import ComputationError

        raise ComputationError(
            f"workdir does not exist: {workdir}. Create it before calling this tool.",
            ms_path=ms_path,
        )

    cmds_path = str(workdir_path / "preflag_cmds.txt")
    script_path = str(workdir_path / "preflag.py")
    cal_ms = str(workdir_path / "calibrators.ms")

    # Always write the flag command list
    cmds_content = _build_cmds_content(
        online_flag_file, shadow_tolerance_m, do_tfcrop, quack_interval_s
    )
    Path(cmds_path).write_text(cmds_content)
    casa_calls.append(f"write_cmds → {cmds_path}")

    n_cmd_lines = len(
        [ln for ln in cmds_content.splitlines() if ln.strip() and not ln.startswith("#")]
    )

    # Always write the script
    script_content = _build_script(
        ms_str, cmds_path, cal_ms, cal_fields, workdir=str(workdir_path), spw=spw
    )
    _debug = debug_mode.validate(debug, debug_params, DEBUG_TASKS)
    if _debug:
        warnings.append(debug_mode.note(_debug))
    write_script(script_path, script_content)
    debug_mode.inject_file(script_path, _debug)
    casa_calls.append(f"write_script → {script_path}")

    base_data: dict = {
        "cmds_path": fmt_field(cmds_path),
        "script_path": fmt_field(script_path),
        "n_flag_commands": fmt_field(n_cmd_lines),
        "cal_fields": cal_fields,
        "spw": spw or None,
        "do_tfcrop": do_tfcrop,
        "quack_interval_s": quack_interval_s,
        "shadow_tolerance_m": shadow_tolerance_m,
        "online_flag_file": online_flag_file or None,
        "cal_ms": fmt_field(None, flag="UNAVAILABLE", note="script not yet executed"),
    }

    if not execute:
        warnings.append(f"Scripts written to {workdir}. Run preflag.py externally.")
        return response_envelope(
            tool_name=TOOL_NAME,
            ms_path=ms_path,
            data=base_data,
            warnings=warnings,
            casa_calls=casa_calls,
        )

    # execute=True: run in-process
    try:
        from casatasks import flagdata, flagmanager, split  # type: ignore[import]

        flagdata = debug_mode.wrap("flagdata", flagdata, _debug)
        split = debug_mode.wrap("split", split, _debug)
    except ImportError:
        from ms_inspect.exceptions import CASANotAvailableError

        raise CASANotAvailableError(
            "casatasks is not installed or cannot be imported.",
            ms_path=ms_path,
        ) from None

    try:
        if _has_flag_version(ms_str, "before_preflag"):
            casa_calls.append(
                "casatasks.flagmanager(mode='restore', versionname='before_preflag', merge='replace')"
            )
            flagmanager(vis=ms_str, mode="restore", versionname="before_preflag", merge="replace")
        else:
            casa_calls.append("casatasks.flagmanager(mode='save', versionname='before_preflag')")
            flagmanager(
                vis=ms_str,
                mode="save",
                versionname="before_preflag",
                comment="Pre-preflag state",
            )
    except Exception as exc:
        from ms_inspect.exceptions import ComputationError

        raise ComputationError(
            f"flagmanager(versionname='before_preflag') failed: {exc}",
            ms_path=ms_path,
        ) from exc

    casa_calls.append(f"casatasks.flagdata(mode='list', inpfile='{cmds_path}', flagbackup=False)")
    try:
        flagdata(
            vis=ms_str,
            mode="list",
            inpfile=cmds_path,
            flagbackup=False,
        )
    except Exception as exc:
        from ms_inspect.exceptions import ComputationError

        raise ComputationError(
            f"flagdata(mode='list') failed: {exc}",
            ms_path=ms_path,
        ) from exc

    casa_calls.append(
        f"casatasks.split(field='{cal_fields}', outputvis='{cal_ms}', "
        f"datacolumn='data', keepflags=False)"
    )
    try:
        _archive_cal_ms(cal_ms, ms_str, str(workdir_path))
        split_kwargs: dict = {
            "vis": ms_str,
            "outputvis": cal_ms,
            "field": cal_fields,
            "datacolumn": "data",
            "keepflags": False,
        }
        if spw:
            split_kwargs["spw"] = spw
        split(**split_kwargs)
    except Exception as exc:
        from ms_inspect.exceptions import ComputationError

        raise ComputationError(
            f"split to calibrators.ms failed: {exc}",
            ms_path=ms_path,
        ) from exc

    # flagdata(action='apply') returns nothing useful, so measure the flagged
    # fraction the pass produced instead of asserting that it worked.
    summary = flagdata(vis=ms_str, mode="summary")
    total = float(summary.get("total") or 0.0)
    flagged_fraction = float(summary["flagged"]) / total if total else None
    record_stage(
        str(workdir_path),
        "preflag",
        ms_str,
        {"flagged_fraction": flagged_fraction},
    )

    record_stage(str(workdir_path), "preflag", cal_ms)
    base_data["flags_applied"] = fmt_field(True)
    base_data["cal_ms"] = fmt_field(cal_ms)
    return response_envelope(
        tool_name=TOOL_NAME,
        ms_path=ms_path,
        data=base_data,
        warnings=warnings,
        casa_calls=casa_calls,
    )
