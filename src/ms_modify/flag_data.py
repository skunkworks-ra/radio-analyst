"""
flag_data.py — ms_flag_data

Flags a caller-named selection of visibilities in a Measurement Set with
flagdata(mode='manual'), with a required reason. The caller (skill) decides
what to flag from a measurement — an ms_calsol_stats outlier, a bad scan in
ms_corrected_stats — and the tool applies it and reports what changed.

This is the preferred route for a bad calibration solution: flag the data that
produced it and re-solve, rather than flagging the solution in the caltable.
The data-side flag is recorded in the MS flag versions and removes the cause
from every later solve; applycal's default applymode='calflag' would discard
the matching target data at apply time anyway.

An empty selection is refused: flagdata(mode='manual') with every selection
empty flags the whole MS. flagbackup=True saves an auto-numbered flag version
(flagdata_N) before each call, so repeated calls never overwrite a backup.

The measurement is scoped to the selection: flagged / total visibilities in
the selection before and after, from flagdata(mode='summary') with the same
selection. A whole-MS fraction is ms_flag_summary's job.

Script output:
  workdir/flag_data.py — self-contained driver script
"""

from __future__ import annotations

from pathlib import Path

from ms_inspect.util.casa_context import validate_ms_path
from ms_inspect.util.formatting import field as fmt_field
from ms_inspect.util.formatting import response_envelope
from ms_inspect.util.logs import write_script
from ms_modify import debug_mode
from ms_modify.manual_selection import validate_manual_selection

TOOL_NAME = "ms_flag_data"
#: CASA tasks this tool calls; the valid debug_params keys (debug_mode.py).
DEBUG_TASKS = ("flagdata",)

# flagdata selections exposed for an MS (feed is unimplemented in CASA; array
# is single-valued for the target telescopes).
SELECTION_KEYS = (
    "antenna",
    "spw",
    "field",
    "scan",
    "timerange",
    "correlation",
    "uvrange",
    "intent",
    "observation",
)


def _build_script(ms_str: str, workdir: str, selection: dict[str, str], reason: str) -> str:
    """Return a self-contained flag_data.py driver script."""
    from ms_inspect.util.stage_log import RECORD_STAGE_SNIPPET as record

    sel = ", ".join(f"{k}={v!r}" for k, v in selection.items())
    return f"""\
#!/usr/bin/env python
\"\"\"
Auto-generated by ms_flag_data (ms_modify).
Run with: python flag_data.py

Manually flags visibilities matching {selection!r}.
Reason: {reason}
\"\"\"
from casatasks import flagdata

{record}

ms_path = {ms_str!r}


def _counts(summary):
    return int(summary.get("flagged", 0)), int(summary.get("total", 0))


before = _counts(flagdata(vis=ms_path, mode="summary", {sel}))
flagdata(vis=ms_path, mode="manual", action="apply", {sel}, flagbackup=True)
after = _counts(flagdata(vis=ms_path, mode="summary", {sel}))

_record_stage({workdir!r}, "flag_data", ms_path, {{
    "selection": {selection!r},
    "selection_flagged_before": before[0],
    "selection_flagged_after": after[0],
    "selection_total": after[1],
}})
print(f"Selection flagged before: {{before[0]}} / {{before[1]}}")
print(f"Selection flagged after:  {{after[0]}} / {{after[1]}}")
"""


def run(
    ms_path: str,
    workdir: str,
    reason: str,
    antenna: str = "",
    spw: str = "",
    field: str = "",
    scan: str = "",
    timerange: str = "",
    correlation: str = "",
    uvrange: str = "",
    intent: str = "",
    observation: str = "",
    execute: bool = False,
    debug: bool = False,
    debug_params: dict | None = None,
) -> dict:
    """
    Generate (and optionally execute) a manual flag of a named MS selection.

    Args:
        ms_path:   Path to the Measurement Set.
        workdir:   Existing directory for the generated script.
        reason:    Required: the measurement that justified the flag. Written
                   into the script header and returned.
        antenna … observation: flagdata selection (SELECTION_KEYS). At least
                   one non-empty entry required.
        execute:   If False (default), write flag_data.py and return. If True,
                   run summary → manual → summary in-process and report the
                   selection's flagged counts before and after.

    Returns:
        Standard response envelope with script_path, selection and reason; when
        execute=True also selection_flagged_before/after and selection_total.
    """
    from ms_inspect.exceptions import ComputationError

    p = validate_ms_path(ms_path)
    ms_str = str(p)
    workdir_path = Path(workdir)
    if not workdir_path.exists():
        raise ComputationError(
            f"workdir does not exist: {workdir}. Create it before calling this tool.",
            ms_path=ms_path,
        )
    selection = dict(
        antenna=antenna,
        spw=spw,
        field=field,
        scan=scan,
        timerange=timerange,
        correlation=correlation,
        uvrange=uvrange,
        intent=intent,
        observation=observation,
    )
    sel = validate_manual_selection(selection, reason, SELECTION_KEYS, "Measurement Set")

    casa_calls: list[str] = []
    warnings: list[str] = []

    script_path = str(workdir_path / "flag_data.py")
    _debug = debug_mode.validate(debug, debug_params, DEBUG_TASKS)
    if _debug:
        warnings.append(debug_mode.note(_debug))
    write_script(script_path, _build_script(ms_str, str(workdir_path), sel, reason.strip()))
    debug_mode.inject_file(script_path, _debug)
    casa_calls.append(f"write_script → {script_path}")

    base_data: dict = {
        "script_path": fmt_field(script_path),
        "selection": sel,
        "reason": reason.strip(),
    }

    if not execute:
        warnings.append(
            f"Script written to {script_path}. Run it externally, or call again with execute=True."
        )
        return response_envelope(
            tool_name=TOOL_NAME,
            ms_path=ms_path,
            data=base_data,
            warnings=warnings,
            casa_calls=casa_calls,
        )

    try:
        from casatasks import flagdata  # type: ignore[import]

        flagdata = debug_mode.wrap("flagdata", flagdata, _debug)
    except ImportError:
        from ms_inspect.exceptions import CASANotAvailableError

        raise CASANotAvailableError(
            "casatasks is not installed or cannot be imported.",
            ms_path=ms_path,
        ) from None

    try:
        before = flagdata(vis=ms_str, mode="summary", **sel)
        casa_calls.append(f"casatasks.flagdata(mode='summary', {sel}) [before]")
        flagdata(vis=ms_str, mode="manual", action="apply", flagbackup=True, **sel)
        casa_calls.append(f"casatasks.flagdata(mode='manual', action='apply', {sel})")
        after = flagdata(vis=ms_str, mode="summary", **sel)
        casa_calls.append(f"casatasks.flagdata(mode='summary', {sel}) [after]")
    except Exception as exc:
        raise ComputationError(
            f"flagdata manual flag on the MS failed: {exc}", ms_path=ms_path
        ) from exc

    from ms_inspect.util.stage_log import record_stage

    record_stage(
        str(workdir_path),
        "flag_data",
        ms_str,
        {
            "selection": sel,
            "selection_flagged_before": int(before.get("flagged", 0)),
            "selection_flagged_after": int(after.get("flagged", 0)),
            "selection_total": int(after.get("total", 0)),
        },
    )
    base_data["selection_flagged_before"] = fmt_field(int(before.get("flagged", 0)))
    base_data["selection_flagged_after"] = fmt_field(int(after.get("flagged", 0)))
    base_data["selection_total"] = fmt_field(int(after.get("total", 0)))
    if int(after.get("total", 0)) == 0:
        warnings.append(
            f"Selection {sel} matched no visibilities; nothing was flagged. Check the "
            "selection against ms_field_list / ms_scan_list / ms_antenna_list."
        )

    return response_envelope(
        tool_name=TOOL_NAME,
        ms_path=ms_path,
        data=base_data,
        warnings=warnings,
        casa_calls=casa_calls,
    )
